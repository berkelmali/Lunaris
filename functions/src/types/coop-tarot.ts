import { Timestamp } from "firebase-admin/firestore";

export type SessionStatus =
  | "PENDING_RECIPIENT"
  | "INITIATOR_DRAWN"
  | "RECIPIENT_DRAWN"
  | "RESOLVED"
  | "EXPIRED";

export interface TarotCard {
  cardId: number;           // 0 - 21 (Major Arcana)
  name: string;             // e.g., "The High Priestess"
  arcana: "MAJOR";
  isReversed: boolean;
  element: "FIRE" | "WATER" | "AIR" | "EARTH";
}

// Stored in subcollection: /coop_sessions/{sessionId}/draws/{uid}
export interface PrivateDrawDocument {
  uid: string;
  card: TarotCard;
  drawnAt: Timestamp;
}

// Stored in root collection: /coop_sessions/{sessionId}
export interface CoopSessionDocument {
  sessionId: string;
  initiatorUid: string;
  recipientUid: string;
  status: SessionStatus;

  // Anti-cheat verification flags
  initiatorHasDrawn: boolean;
  recipientHasDrawn: boolean;

  // Populated ONLY when status flips to RESOLVED
  revealedCards?: {
    initiatorCard: TarotCard;
    recipientCard: TarotCard;
  };

  // Synthesis payload generated by the Cloud Function
  synthesisPayload?: {
    compositeResonanceScore: number; // 0 - 100%
    elementalAlchemy: string;        // e.g. "Fire + Water"
    relationalTheme: string;
    actionableInsight: string;
    calculatedAt: Timestamp;
  };

  createdAt: Timestamp;
  expiresAt: Timestamp;             // TTL timestamp (createdAt + 12h)
}
